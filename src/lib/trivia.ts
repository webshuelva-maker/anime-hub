export function pickTrivia(seed: number): string {
  return ANIME_TRIVIA[seed % ANIME_TRIVIA.length];
}

/** Devuelve los índices de todas las curiosidades en un orden aleatorio distinto cada vez. */
export function shuffledTriviaOrder(): number[] {
  const order = ANIME_TRIVIA.map((_, i) => i);
  for (let i = order.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [order[i], order[j]] = [order[j], order[i]];
  }
  return order;
}

const QUEUE_KEY = "anime-hub:trivia-queue";
const POSITION_KEY = "anime-hub:trivia-position";

/**
 * Sigue la baraja de curiosidades de una noticia a otra (no solo dentro de
 * una misma espera) — no repite ninguna hasta haberlas visto todas, ni
 * aunque abras varias noticias seguidas.
 */
export function nextTriviaIndex(): number {
  if (typeof window === "undefined") return Math.floor(Math.random() * ANIME_TRIVIA.length);

  let queue: number[] = [];
  try {
    queue = JSON.parse(window.localStorage.getItem(QUEUE_KEY) || "[]");
  } catch {
    queue = [];
  }
  let position = Number(window.localStorage.getItem(POSITION_KEY) || "0");

  if (queue.length !== ANIME_TRIVIA.length || position >= queue.length) {
    queue = shuffledTriviaOrder();
    position = 0;
    window.localStorage.setItem(QUEUE_KEY, JSON.stringify(queue));
  }

  const index = queue[position];
  window.localStorage.setItem(POSITION_KEY, String(position + 1));
  return index;
}
